/**
 * Что такое «долг поставщику» — в одном месте на всю систему.
 *
 * Зеркало `receivables.ts`, но источник у него другой, и это главное решение
 * файла. Закупочного заказа в системе нет вовсе: обязательство перед
 * поставщиком возникает **приходом на склад** — `stock_move` с типом
 * `receipt`, поставщиком и суммой `cost_total`. Гасится оно проведённым
 * платежом: расходная операция с корсчётом вида `payable` и тем же
 * контрагентом.
 *
 * Сальдо счёта 6010 источником быть не может, хотя соблазн велик: в него
 * пишется только оплата, кредита по приходу нет, и «долг» по нему вышел бы
 * отрицательным — чем больше заплатили, тем больше должны. Проверка на это
 * стоит отдельная.
 *
 * Срока оплаты у прихода нет — его не на чем записать. Берём отсрочку
 * контрагента (`payment_delay_days`), ту же, по которой живёт дебиторка:
 * второй справочник сроков разошёлся бы с первым.
 */

/** Приход от поставщика: откуда берётся обязательство. */
export const SUPPLY_WHERE = `m.operation_type = 'receipt' AND m.partner_id IS NOT NULL AND m.cost_total > 0`;

/** Проведённая оплата поставщику: чем обязательство гасится. */
export const SUPPLY_PAID_WHERE =
  `o.status = 'posted' AND o.operation_type = 'expense' ` +
  `AND ca.kind = 'payable' AND o.partner_id IS NOT NULL`;

/**
 * Непогашенный остаток прихода при разнесении оплат **FIFO**.
 *
 * `running` — нарастающий итог приходов контрагента от старых к новым,
 * `paid` — всё, что ему заплачено. Приход закрыт, пока нарастающий итог не
 * перерос оплату; дальше открыт ровно хвост.
 *
 * Разносить оплату «в среднем», долей на каждый приход, нельзя: тогда у
 * каждого поставщика, которому хоть что-то платили, оставался бы непогашенный
 * хвост в самой старой корзине, и отчёт показывал бы просрочку там, где её
 * давно закрыли. FIFO гасит старое первым — так платят и так спрашивают.
 */
export const SUPPLY_OPEN_EXPR = `least(r.amount, greatest(r.running - coalesce(p.paid, 0), 0))`;

/**
 * Срок оплаты прихода: дата прихода плюс отсрочка контрагента.
 *
 * Отсрочки нет — значит платить надо было в день прихода, и просрочка идёт с
 * него же. Это строже, чем «срок не назначен», и так и должно быть: товар
 * получен, а когда за него платить, не договорились.
 */
export const SUPPLY_DUE_EXPR = `(r.doc_date + coalesce(pt.payment_delay_days, 0))`;
