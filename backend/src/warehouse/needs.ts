/**
 * Потребность в закупке: сам расчёт (ТЗ 5.10).
 *
 * Чистый модуль без Nest и без базы — по той же причине, что и кодирование
 * этикеток: расчёт «сколько дозаказать» проверяется числами, а не запросами,
 * и разбирать его вместе с четырьмя джойнами значит не разобрать вовсе.
 *
 * Три величины из ТЗ 5.5 (наличие, резерв, доступное) здесь дополняются
 * четвёртой — плановым расходом. Без неё цифра врёт ровно тем способом, от
 * которого ТЗ и предостерегает: на складе десять тонн, свободны они только до
 * того момента, как цех начнёт выдавать материалы по уже запущенным заказам.
 */

/** Уровни по позиции. Ноль значит «уровень не задан», а не «ноль штук». */
export interface NeedLevels {
  minQty: number;
  criticalQty: number;
}

export interface NeedStock {
  /** Что лежит на складе. */
  onHand: number;
  /**
   * Что обещано покупателям активными резервами.
   *
   * Берётся из `stock_reservation`, а не из `stock_balance.qty_reserved`:
   * остаток обрезан наличием (на нём CHECK `qty_reserved <= qty_on_hand`), и
   * резерв сверх наличия — законный случай по праву `sales.order.oversell` —
   * в остатке выглядел бы как его отсутствие. Потребность в закупке именно про
   * этот случай и спрашивают.
   */
  promised: number;
  /**
   * Плановый расход по запущенным производственным заказам, ещё не выданный
   * в цех: план минус выданное по строкам материалов.
   *
   * Выданное вычитается, потому что оно уже ушло со склада движением и в
   * наличии его нет — сложив план целиком, мы посчитали бы выдачу дважды.
   */
  plannedOut: number;
}

export type NeedState = 'critical' | 'below_min' | 'ok';

export interface NeedNumbers {
  /** Доступное по ТЗ 5.5: наличие минус обещанное. Бывает отрицательным. */
  available: number;
  /** Доступное после того, как цех выберет свой план. */
  projected: number;
  /** Сколько дозаказать, чтобы вернуться к минимальному уровню. */
  needQty: number;
  state: NeedState;
}

/**
 * Хвосты float в шестом знаке. Количества в базе — `decimal(20,6)`, и
 * `0.1 + 0.2` в ответе выглядит поломкой расчёта, а не свойством double.
 */
const round6 = (v: number) => Number(v.toFixed(6));

/** Порог сравнения: младший разряд количества — шестой знак. */
const EPS = 1e-9;

/**
 * Состояние определяется по **доступному**, а потребность — по доступному с
 * планом. Это не разнобой, а две разные вещи из одного абзаца ТЗ 5.10:
 * «при падении доступного ниже уровня» позиция попадает в отчёт, а «в
 * потребности учитываются открытые резервы и плановый расход».
 *
 * Иначе говоря: тревога поднимается по тому, что есть сейчас, а заказывать
 * надо с оглядкой на то, что уже обещано складом цеху.
 */
export function calcNeed(levels: NeedLevels, stock: NeedStock): NeedNumbers {
  const available = round6(stock.onHand - stock.promised);
  const projected = round6(available - stock.plannedOut);

  const state: NeedState =
    levels.criticalQty > 0 && available < levels.criticalQty - EPS
      ? 'critical'
      : levels.minQty > 0 && available < levels.minQty - EPS
        ? 'below_min'
        : 'ok';

  // Дозаказ считается до минимального уровня, а не до критического: критический
  // — это порог тревоги, возвращаться на него значит заказывать ровно столько,
  // чтобы завтра снова быть в тревоге.
  const target = levels.minQty > 0 ? levels.minQty : levels.criticalQty;
  const needQty = target > 0 ? round6(Math.max(0, target - projected)) : 0;

  return { available, projected, needQty, state };
}

/**
 * Попадает ли позиция в отчёт.
 *
 * В отчёте не только «ниже уровня», но и всё, что уже нечем закрыть: доступное
 * в минусе значит, что обещано больше, чем лежит, — и уровень тут ни при чём.
 * Без этой второй половины позиция без заданного уровня уходила бы из отчёта
 * молча, а именно её и не хватает на отгрузке.
 */
export function isNeeded(numbers: NeedNumbers): boolean {
  return numbers.state !== 'ok' || numbers.needQty > EPS || numbers.projected < -EPS;
}
