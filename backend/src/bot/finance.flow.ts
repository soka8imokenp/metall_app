/**
 * Разбор того, что человек написал словами, и формат того, что он прочтёт.
 *
 * Отдельным файлом без зависимостей: это чистые функции, и проверяются они
 * без базы, без Telegram и без Nest. Ошибка здесь дороже остальных — она
 * превращается в неверную сумму или не ту дату в деньгах.
 */

/**
 * Общее для всех разделов — деньги и даты — лежит в `format.ts`: срок оплаты в
 * заказе разбирается теми же правилами, что дата платежа. Здесь оставлено то,
 * что про деньги финансов: разбор суммы операции.
 */
export { BASE_CURRENCY, moment, parseDay, shiftDay, showDay, sum, today } from './format.js';

/**
 * Сумма из сообщения.
 *
 * Пробелы, неразрывные пробелы и апострофы выкидываем: человек пишет
 * «1 500 000», и отказать ему за это нельзя. Запятая и точка — одно и то же:
 * на телефоне разделитель зависит от раскладки, а не от желания.
 *
 * Чего не принимаем — сокращений вроде «500к» и «пол миллиона». В деньгах
 * догадка дороже вопроса: лучше переспросить, чем записать не ту сумму.
 */
export function parseAmount(raw: string): string | null {
  const cleaned = raw.replace(/[\s\u00a0\u202f'`’]/g, '').replace(',', '.');
  if (!/^\d{1,15}(\.\d{1,2})?$/.test(cleaned)) return null;
  const value = Number(cleaned);
  if (!Number.isFinite(value) || value <= 0) return null;
  return String(value);
}

export type FlowStep =
  | 'company'
  | 'amount'
  | 'item'
  | 'account'
  | 'partner'
  | 'date'
  | 'comment'
  | 'confirm'
  /**
   * Разговор вне мастера: бот ждёт фотографию чека к уже заведённой операции.
   * В список вопросов он не входит — это не шаг заполнения, а ожидание файла.
   */
  | 'photo';

/**
 * Незаконченный разговор: что человек уже ответил и о чём его спрашивают.
 *
 * Названия выбранного хранятся рядом с идентификаторами. Это не дублирование
 * ради удобства: экран подтверждения и экран любого следующего шага должны
 * показать «Касса», а не «5010», и лазить за названием в базу на каждую правку
 * подписи — пять запросов там, где хватает того, что уже прочитали.
 */
export interface Flow {
  /** Чей разговор: раздел читает только свой. */
  kind: 'fin';
  type: 'income' | 'expense';
  step: FlowStep;
  companyUid?: string;
  companyName?: string;
  amount?: string;
  itemUid?: string;
  itemName?: string;
  accountCode?: string;
  accountName?: string;
  currency?: string;
  partnerUid?: string;
  partnerName?: string;
  /**
   * Заказ, который оплачивают этим поступлением. Пока он задан, разговор идёт
   * короче: компанию, покупателя и валюту спрашивать не у кого — они в заказе.
   */
  orderUid?: string;
  orderNumber?: string;
  /** Свободный остаток по заказу на момент начала разговора. */
  orderRemaining?: string;
  /** Статья подставлена сама: в компании она одна, выбирать не из чего. */
  itemFixed?: boolean;
  /**
   * Повтор прошлой записи: всё, кроме суммы и даты, взято из неё. Зарплата,
   * аренда и связь приходят каждый месяц одними и теми же, и проходить из-за
   * них восемь экранов — та работа, от которой бот должен избавлять.
   */
  repeat?: boolean;
  /** Номер записи, с которой списано: человек должен видеть, что повторяет. */
  repeatOf?: string;
  /** Сумма прошлой записи — ею же чаще всего и платят. */
  repeatAmount?: string;
  /** К какой операции ждём фото чека. */
  photoFor?: string;
  photoNumber?: string;
  day?: string;
  comment?: string;
  /**
   * Ключ повторной отправки. Заводится один раз, когда человек дошёл до
   * проверки, и живёт до конца мастера: второе нажатие «Записать» — у бота это
   * обычное дело — вернёт ту же операцию, а не заведёт вторую такую же.
   */
  key?: string;
}

/**
 * Порядок вопросов. Компанию спрашиваем только у того, у кого их несколько:
 * единственную выбирать не из чего, а лишний экран человек в возрасте читает
 * как ещё одну возможность ошибиться.
 *
 * У платежа по заказу список короче по той же причине: компания, покупатель и
 * валюта заданы заказом, а статья — когда она в компании одна. Спрашивать
 * известное значит дать возможность ответить неверно.
 */
export function order(
  flow: Pick<Flow, 'orderUid' | 'itemFixed' | 'repeat'>,
  many: boolean,
): FlowStep[] {
  // Повтор: статья, счёт, контрагент и компания уже известны из прошлой
  // записи. Остаются сумма и дата — остальное человек правит кнопкой «Назад».
  if (flow.repeat) return ['amount', 'date', 'confirm'];
  if (flow.orderUid) {
    return [
      'amount',
      ...(flow.itemFixed ? [] : (['item'] as FlowStep[])),
      'account',
      'date',
      'comment',
      'confirm',
    ];
  }
  return [
    ...(many ? (['company'] as FlowStep[]) : []),
    'amount',
    'item',
    'account',
    'partner',
    'date',
    'comment',
    'confirm',
  ];
}

/** Следующий шаг после текущего. Последний — `confirm`, дальше некуда. */
export function nextStep(flow: Flow, many: boolean): FlowStep {
  const all = order(flow, many);
  return all[Math.min(all.indexOf(flow.step) + 1, all.length - 1)]!;
}

/** Предыдущий шаг. Для первого — `null`: назад из него только выход. */
export function prevStep(flow: Flow, many: boolean): FlowStep | null {
  const all = order(flow, many);
  const i = all.indexOf(flow.step);
  return i <= 0 ? null : all[i - 1]!;
}
