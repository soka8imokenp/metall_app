import type { CellValue } from './xlsx.js';

/**
 * Отчёт — это таблица: заголовки колонок и строки значений.
 *
 * Форма одна на все модули, потому что выгрузка одна: `buildXlsx` и `buildCsv`
 * берут ровно её. Если бы каждый модуль описывал отчёт по-своему, выгрузка
 * знала бы про каждый, и в Excel рано или поздно уехало бы не то, что на
 * экране, — спорить об этом пришлось бы с заказчиком.
 *
 * Числа в строках — числа, а не подписанные строки: в Excel по колонке берётся
 * сумма, а формат («313,4 т») собирается там, где показывают.
 */
export interface ReportColumn {
  title: string;
  /** Числовая колонка: в Excel уходит числом, в CSV — с десятичной запятой. */
  numeric?: boolean;
  width?: number;
}

export interface ReportTable {
  /** Заголовок отчёта: он же имя листа и основа имени файла. */
  title: string;
  /** Что именно попало в отчёт: период, срез, число строк. */
  subtitle: string;
  columns: ReportColumn[];
  rows: CellValue[][];
  /** Сколько строк отдано. Больше предела отчёт не отдаёт и говорит об этом. */
  total: number;
  truncated: boolean;
}
