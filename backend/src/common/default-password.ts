/**
 * Правило дефолтного пароля — в одном файле, потому что его знают трое:
 * сервер (чтобы не дать поставить такой пароль себе «новым»), сид (чтобы его
 * выдать) и разовый скрипт учёток стенда. Пока правило жило в каждом из них
 * своей строкой, оно разъехалось: сид выдавал `owner1123`, а заказчик просил
 * `owner123`.
 *
 * Правило (Отабек, 06.10): **название роли** плюс `123` — «admin — admin123,
 * owner1 — owner123, owner2 — owner123». Хвостовой номер логина на пароль не
 * влияет: двое собственников — два человека в одной роли, дефолтный пароль у
 * них общий. У логинов без номера правило совпадает с «логин + 123».
 *
 * Файл намеренно без зависимостей: его тянет и сид, и скрипт, и Nest.
 */
export const defaultPasswordFor = (login: string) => `${login.replace(/\d+$/, '')}123`;
