import { currentContext } from './request-context.js';

/**
 * Текст на языке того, кто спросил (ТЗ 13.4).
 *
 * Русский стоит первым: это язык кода, журналов и разговора с заказчиком, и
 * при чтении исходника видно, о чём речь, без перевода обратно. Узбекский
 * берётся, только когда язык запроса узбекский.
 *
 * Вне запроса (миграция, посев, воркер расшифровки) контекста нет — отвечаем
 * по-русски, а не падаем: это не ошибка программиста, а работа без человека.
 */
export function say(ru: string, uz: string): string {
  return currentContext()?.locale === 'uz' ? uz : ru;
}

/** Язык запроса, когда текст собирается не из двух кусков, а по месту. */
export function isUz(): boolean {
  return currentContext()?.locale === 'uz';
}
