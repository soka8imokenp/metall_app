import { Prisma } from '../generated/prisma/client.js';
import { isUz } from './say.js';

/**
 * Название из справочника на языке запроса.
 *
 * Справочники двуязычны: у номенклатуры, складов, контрагентов, участков,
 * причин и статей есть `name_ru` и `name_uz`. Запрос, жёстко выбиравший
 * `name_ru`, показывал русское название на узбекском экране — и в выгрузке
 * тоже, где выбрать поле на стороне экрана уже нельзя.
 *
 * Подставляется куском SQL, а не параметром: имя колонки параметром не
 * бывает. Поэтому псевдоним таблицы проверяется — в запрос попадает только
 * то, что похоже на псевдоним.
 */
export function nameCol(alias: string): Prisma.Sql {
  if (!/^[a-z_][a-z0-9_]*$/i.test(alias)) {
    throw new Error(`Псевдоним таблицы «${alias}» не похож на псевдоним`);
  }
  return Prisma.raw(`${alias}.${isUz() ? 'name_uz' : 'name_ru'}`);
}
