/**
 * Сумма прописью (ТЗ 7.1).
 *
 * Проверка без базы: это чистая функция, и ломается она на согласованиях —
 * род тысячи, склонение разряда, одиннадцать против одного.
 */
import { describe, expect, it } from 'vitest';
import { amountInWords, plural } from '../src/documents/amount-words.js';

describe('склонение разряда', () => {
  const forms: [string, string, string] = ['сум', 'сума', 'сумов'];
  it('1, 2–4 и 5–20 берут разные формы', () => {
    expect(plural(1, forms)).toBe('сум');
    expect(plural(3, forms)).toBe('сума');
    expect(plural(7, forms)).toBe('сумов');
  });
  it('11–14 идут по третьей форме, хотя кончаются на 1–4', () => {
    for (const n of [11, 12, 13, 14, 111, 214]) expect(plural(n, forms)).toBe('сумов');
  });
  it('21 и 22 берут форму по последней цифре', () => {
    expect(plural(21, forms)).toBe('сум');
    expect(plural(22, forms)).toBe('сума');
  });
});

describe('доли тийина', () => {
  const w = (v: string) => amountInWords(v, 'UZS');

  /**
   * Сумма в базе держит четыре знака (цена за тонну бывает с четырьмя), а на
   * экране и на бумаге стоит два. Пропись обязана округлять ту же цифру, что
   * видит человек: иначе в шапке «…,45», а словами «44 тийина» — счёт спорит
   * сам с собой, и клиент вправе его не принять.
   */
  it('округляет дробную часть, а не отбрасывает её', () => {
    expect(w('100.4450')).toContain('45 тийинов');
    expect(w('100.4449')).toContain('44 тийина');
    expect(w('100.9950')).toContain('Сто один сум 00 тийинов');
    expect(w('100.9950')).not.toContain('99 тийинов');
  });
});

describe('сумма прописью по-русски', () => {
  const w = (v: string) => amountInWords(v, 'UZS');

  // «тийин» склоняется как существительное мужского рода 2-го склонения,
  // род. мн. — «тийинов» (Викисловарь, ru.wiktionary.org/wiki/тийин).
  // Первая версия этой проверки ждала несклоняемое «тийин» — неверно.

  it('ноль пишется словом, а не пустой строкой', () => {
    expect(w('0.00')).toBe('Ноль сумов 00 тийинов');
  });

  it('у тысячи женский род, у миллиона мужской', () => {
    expect(w('1000.00')).toBe('Одна тысяча сумов 00 тийинов');
    expect(w('2000.00')).toBe('Две тысячи сумов 00 тийинов');
    expect(w('1000000.00')).toBe('Один миллион сумов 00 тийинов');
    expect(w('2000000.00')).toBe('Два миллиона сумов 00 тийинов');
  });

  it('пропущенный разряд не оставляет лишних слов', () => {
    expect(w('1000001.00')).toBe('Один миллион один сум 00 тийинов');
    expect(w('1000100.00')).toBe('Один миллион сто сумов 00 тийинов');
  });

  it('копейки идут цифрами: их подделать нечем, а место они экономят', () => {
    expect(w('123.45')).toBe('Сто двадцать три сума 45 тийинов');
    expect(w('11.00')).toBe('Одиннадцать сумов 00 тийинов');
    expect(w('21.00')).toBe('Двадцать один сум 00 тийинов');
  });

  it('настоящая сумма из посева', () => {
    expect(w('269811704.9034')).toBe(
      'Двести шестьдесят девять миллионов восемьсот одиннадцать тысяч семьсот четыре сума 90 тийинов',
    );
  });

  it('валюта меняет слово, незнакомая пишется кодом', () => {
    expect(amountInWords('5.00', 'USD')).toBe('Пять долларов 00 центов');
    expect(amountInWords('5.00', 'EUR')).toBe('Пять EUR');
  });

  it('минус называется словом, а не знаком', () => {
    expect(w('-1.00')).toBe('Минус один сум 00 тийинов');
  });
});

describe('сумма прописью по-узбекски', () => {
  const w = (v: string) => amountInWords(v, 'UZS', 'uz');

  it('разряды пишутся без согласования', () => {
    expect(w('2000.00')).toBe('Ikki ming so‘m 00 tiyin');
    expect(w('21.00')).toBe('Yigirma bir so‘m 00 tiyin');
  });

  it('«bir ming» не говорят — просто ming', () => {
    expect(w('1000.00')).toBe('Ming so‘m 00 tiyin');
    expect(w('1000000.00')).toBe('Bir million so‘m 00 tiyin');
  });

  it('сотни идут парой: «uch yuz»', () => {
    expect(w('345.00')).toBe('Uch yuz qirq besh so‘m 00 tiyin');
  });
});
