import { describe, expect, it } from 'vitest';
import { share } from '../src/sales/sales.service.js';

/**
 * Ветка «делить не на что» в живых данных недостижима: у всех покупателей из
 * сида лимит задан. Но именно она держит обещание экрана — не показывать
 * «0% выборки» там, где лимит просто не завели.
 */
describe('share', () => {
  it('нулевая база — доли нет, а не ноль процентов', () => {
    expect(share(0, 0)).toBeNull();
    expect(share(150, 0)).toBeNull();
  });

  it('обычная доля — одна цифра после точки, точка машинная', () => {
    expect(share(1, 2)).toBe('50.0');
    expect(share(1, 3)).toBe('33.3');
    expect(share(0, 3)).toBe('0.0');
  });

  it('выборка сверх лимита не обрезается: превышение надо видеть', () => {
    expect(share(150, 100)).toBe('150.0');
  });
});
