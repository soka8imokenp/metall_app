-- Ключ сайта заводится сразу, по одному на компанию.
--
-- Иначе подключение сайта начинается с похода в CRM за ключом, а до тех пор
-- форма слать некуда. Ключ инертен: пока его не вставили на сайт, по нему
-- ничего не приходит. Имя говорит, что он заготовка — его переименуют или
-- выключат и заведут свой.
INSERT INTO "site_key" ("company_id", "code", "name")
SELECT c.id,
       replace(gen_random_uuid()::text, '-', ''),
       'Сайт компании (заготовка)'
  FROM "company" c
 WHERE NOT EXISTS (SELECT 1 FROM "site_key" k WHERE k.company_id = c.id);
