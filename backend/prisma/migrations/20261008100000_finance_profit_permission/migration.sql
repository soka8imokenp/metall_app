-- Право «Финансовый результат: прибыль и маржа» (требование заказчика со
-- встречи 07.10.2026: финансист видит аналитику, но не чистую прибыль
-- учредителей).
--
-- Право заводится миграцией, а не только посевом. Посев обнуляет справочники и
-- собирает их из `prisma/rbac.ts` — на свежей установке право появится оттуда.
-- Но стенд и рабочая база пересева не переживут (сотрутся данные, сбросятся
-- пароли), а права читаются из базы: без этой вставки право существовало бы
-- только в коде. Тогда его не было бы ни у кого, включая учредителя, и отчёт
-- о прибыли закрылся бы вообще для всех.
INSERT INTO "permission" ("code", "module", "description_ru", "description_uz")
VALUES (
  'finance.profit.view',
  'finance',
  'Финансовый результат: прибыль и маржа',
  'Moliyaviy natija: foyda va marja'
)
ON CONFLICT ("code") DO NOTHING;

-- Кому оно достаётся. Ровно те же три системные роли, что получают его по
-- правилам `rbac.ts`: администратор (все права), директор (все, кроме
-- `admin.*`), собственник (все `.view`). Бухгалтеру и кладовщику — нет, в этом
-- и смысл требования.
--
-- Роли компаний, собранные руками на экране «Роли и права», здесь не
-- затрагиваются: новое право выдаётся осознанно, а не достаётся всем,
-- у кого уже был доступ к финансам.
INSERT INTO "role_permission" ("role_id", "permission_id")
SELECT r.id, p.id
  FROM "role" r
  JOIN "permission" p ON p.code = 'finance.profit.view'
 WHERE r.company_id IS NULL
   AND r.code IN ('admin', 'director', 'owner')
ON CONFLICT DO NOTHING;
