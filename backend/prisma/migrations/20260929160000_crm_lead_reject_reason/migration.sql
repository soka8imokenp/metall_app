-- Причина отказа по обращению (ТЗ 8.1, отчёт по причинам отказов).
--
-- Комментарий заявки для этого не годится: в нём записано, что человек
-- спрашивал, а не почему он ушёл. Одно поле на два смысла означало бы, что
-- отчёт по причинам отказов считает пересказ разговора.

ALTER TABLE "lead" ADD COLUMN "reject_reason" TEXT;

-- Отклонённое обращение без причины не наполняет отчёт: правило держит база,
-- а не только сервис. NOT VALID — уже лежащие строки сида не переписываем
-- задним числом, проверка действует на новые и на правки.
ALTER TABLE "lead"
  ADD CONSTRAINT "lead_rejected_needs_reason"
  CHECK (status <> 'rejected' OR "reject_reason" IS NOT NULL) NOT VALID;
