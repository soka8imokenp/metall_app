-- Готовый PDF документа (ТЗ 7.2).
--
-- PDF не собирается заново на каждое скачивание. Преобразование делает
-- LibreOffice: это отдельный процесс, полсекунды и десятки мегабайт памяти.
-- Счёт скачивают, отправляют, печатают и скачивают снова — четыре запуска
-- на один и тот же неизменившийся файл.
--
-- Байты лежат в хранилище вложений, а не в строке: здесь только ключ. PDF
-- тяжелее шаблона на порядок (сотни килобайт против пары), и класть его в
-- таблицу значило бы тащить его в каждый дамп и в каждый `SELECT *`.
ALTER TABLE "document" ADD COLUMN "pdf_key"      TEXT;
ALTER TABLE "document" ADD COLUMN "pdf_size"     INTEGER;
ALTER TABLE "document" ADD COLUMN "pdf_built_at" TIMESTAMPTZ;

-- Версия документа, из которой собран PDF.
--
-- Пока правка утверждённого документа не заводит новую версию (это Э6),
-- поле всегда равно текущей версии. Заводится оно здесь, а не там, потому
-- что без него правка молча отдавала бы старый PDF: файл есть, ключ есть,
-- и повода пересобрать нет.
ALTER TABLE "document" ADD COLUMN "pdf_version"  INTEGER;
