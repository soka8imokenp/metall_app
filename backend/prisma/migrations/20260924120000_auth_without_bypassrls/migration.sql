-- Вход в систему без обхода RLS.
--
-- До этой миграции сервис держал второе подключение ролью metall_owner
-- (BYPASSRLS) — открытым всё время работы процесса. Нужно оно было ровно для
-- одного: проверить логин и собрать профиль до того, как известны компании
-- пользователя. То есть ради четырёх таблиц в рантайме был открыт обход
-- политик для всех пятидесяти двух.
--
-- Замкнутый круг рвётся одной политикой. Учётные записи, журнал входов и
-- справочники прав политик не несут вовсе — это не данные арендатора. Мешало
-- только `user_role_assignment`: у него есть company_id, и общая политика
-- company_isolation требует контекст, которого на входе ещё нет.
--
-- Своё назначение пользователь видит по app.user_id. Политики PERMISSIVE
-- складываются по ИЛИ, поэтому company_isolation продолжает работать как
-- работала, а own_assignments добавляет к ней собственные строки входящего.
-- Контекст не выставлен — app.current_user_id() возвращает NULL, сравнение
-- даёт NULL, строк нет: отказ закрытый, как и у остальных политик.
--
-- Побочный эффект, осознанный: при суженном X-Company-Id пользователь видит
-- свои назначения и в тех своих компаниях, которые заголовком отсечены. Это
-- его собственные права доступа, а не данные отсечённой компании.

CREATE POLICY own_assignments ON user_role_assignment
  FOR SELECT
  USING (user_id = app.current_user_id());
