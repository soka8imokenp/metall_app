-- Системная роль «Собственник» (ТЗ 3.2: «отдельные уровни доступа для
-- учредителей и руководителей», задача Отабека от 06.10).
--
-- Роль заводится миграцией, а не только посевом. Посев обнуляет справочники и
-- пересобирает их из `prisma/rbac.ts` — на свежей установке роль появится
-- оттуда. Но стенд и рабочая база пересева не переживут (сотрутся данные), а
-- роли на экране «Роли и права» читаются из базы: без этой вставки роль
-- существовала бы только в коде, и назначить её было бы некому.
--
-- Состав прав — правилом, а не списком: все права на просмотр. То же правило
-- стоит в `rbac.ts`, и сторож `test/rbac-roles.spec.ts` держит их вместе.
-- Собственник смотрит свою компанию целиком, включая финансы и отчёты, и не
-- делает в ней ничего: ни одного `admin.*`, ни одного права на запись. Своей
-- компанией его ограничивает назначение, а не права.
-- Повторную вставку отбивает `NOT EXISTS`, а не `ON CONFLICT`: уникальный
-- индекс по (company_id, code) у системной роли не работает — company_id там
-- NULL, а NULL в Postgres не равен NULL, и второй такой же ряд индекс пустит.
INSERT INTO "role" ("code", "name_ru", "name_uz", "is_system", "company_id")
SELECT 'owner', 'Собственник', 'Mulkdor', true, NULL
 WHERE NOT EXISTS (
   SELECT 1 FROM "role" WHERE "code" = 'owner' AND "company_id" IS NULL
 );

INSERT INTO "role_permission" ("role_id", "permission_id")
SELECT r.id, p.id
  FROM "role" r
  JOIN "permission" p ON p.code LIKE '%.view'
 WHERE r.code = 'owner' AND r.company_id IS NULL
ON CONFLICT DO NOTHING;
