-- Признак «пароль временный» (требование Отабека от 06.10).
--
-- Ставится там, где пароль придумал не сам человек: при заведении учётки и
-- при сбросе руководителем. Снимается только самостоятельной сменой пароля
-- через `POST /auth/me/password`.
--
-- Значение по умолчанию `false`, а не `true`: существующие учётки свой пароль
-- уже меняли или получили его из рук в руки, и поднимать признак всем задним
-- числом значит на один прогон миграции запереть весь стенд. Учётки стенда
-- приводит к новой схеме отдельный одноразовый скрипт
-- `scripts/rbac-stand-accounts.ts`.
--
-- Политик RLS на `user_account` нет и здесь не появляется: учётные записи —
-- не данные арендатора, подробности в `prisma.service.ts` и в миграции
-- `auth_without_bypassrls`.
ALTER TABLE "user_account"
  ADD COLUMN "must_change_password" boolean NOT NULL DEFAULT false;
