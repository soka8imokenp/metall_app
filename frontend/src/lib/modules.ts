import type { AppModule } from '../context/AppContext';

/**
 * Какое право открывает раздел (ТЗ 3.3).
 *
 * Одна таблица на всё приложение, а не отдельное условие в сайдбаре и ещё
 * одно в `App.tsx`: разъехавшись, они дают худшее из возможного — пункт меню
 * есть, а раздел пустой, или наоборот.
 *
 * Здесь только **вход** в раздел. Что человек может внутри — решают свои
 * права на местах (`can('finance.post')` и подобные), и решает их сервер:
 * спрятанная кнопка никого не останавливает, адрес набирается руками.
 * Сторож на стороне сервера — `backend/test/role-access.e2e.spec.ts`.
 *
 * «Настройки» открываются двумя правами, и это не придирка: управление
 * ролями без управления людьми — рабочая раздача прав, и запирать такого
 * администратора снаружи раздела нельзя.
 */
export const MODULE_PERMISSIONS: Record<AppModule, string[]> = {
  dashboard: ['dashboard.view'],
  sales: ['sales.view'],
  warehouse: ['warehouse.view'],
  production: ['production.view'],
  finance: ['finance.view'],
  documents: ['documents.view'],
  crm: ['crm.view'],
  admin: ['admin.users', 'admin.roles'],
  /**
   * «Справка» открыта любому, кто вошёл: инструкция по разделу, которого у
   * человека нет, ему и не покажется — это решает отбор статей
   * (`help/access.ts`). А запирать сам раздел значит оставить без инструкции
   * рабочего цеха, у которого прав меньше всех.
   */
  help: [],
};

/**
 * Открыт ли раздел человеку с такими правами.
 *
 * Пустой список прав — раздел открыт всем вошедшим. Через `some` этого не
 * выразить: у пустого массива он всегда `false`, и «Справка» оказалась бы
 * закрыта вообще для всех.
 */
export const moduleAllowed = (module: AppModule, can: (p: string) => boolean) => {
  const need = MODULE_PERMISSIONS[module];
  return need.length === 0 || need.some(can);
};

/**
 * Первый открытый раздел — куда вести, когда запрошенный закрыт.
 *
 * Порядок тот же, что в меню: человек попадает на самый верхний из доступных,
 * а не на случайный. `dashboard` здесь не особый: право на сводку тоже можно
 * снять, и тогда роль обязана открываться на чём-то, что ей видно.
 */
export const MODULE_ORDER: AppModule[] = [
  'dashboard',
  'sales',
  'warehouse',
  'production',
  'finance',
  'documents',
  'crm',
  'admin',
  // Последней: роль обязана открываться на разделе с её работой, а не на
  // инструкции к ней. Но без вообще ни одного открытого раздела открывать
  // нечего — и тогда справка лучше пустого экрана.
  'help',
];

export const firstAllowedModule = (can: (p: string) => boolean): AppModule | null =>
  MODULE_ORDER.find((m) => moduleAllowed(m, can)) ?? null;
